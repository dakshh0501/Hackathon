// Unified search function matching names, states, or aliases
export function searchDestinationData(query) {
  if (!query || typeof query !== 'string') return null;
  const q = query.trim().toLowerCase();
  if (!q) return null;

  return DESTINATIONS.find(dest => {
    if (dest.name.toLowerCase().includes(q)) return true;
    if (dest.id.toLowerCase().includes(q)) return true;
    if (dest.aliases && dest.aliases.some(alias => alias.toLowerCase().includes(q) || q.includes(alias.toLowerCase()))) {
      return true;
    }
    return false;
  }) || null;
}
